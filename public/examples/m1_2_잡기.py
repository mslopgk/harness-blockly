# [중등 1-②] 잡기 — 찾은 그 자리로 가서 집기
#
# ①찾기 를 그대로 담고 있고, 뒤에 '집기'가 붙었다. 이 파일 하나만 열어도 돌아간다.
#
# 새로 배우는 것: 카메라가 본 자리는 **픽셀**(사진 위의 점)이고 로봇이 아는 자리는
# **mm** 다. robotvision.to_robot 이 픽셀을 로봇 자리로 바꿔 준다.
# ※ 미리 로봇 패널 → '자리 맞추기'를 한 번 해 두어야 한다.
#
# 이 수업 로봇에 달린 것은 **집게(그리퍼)** 라서 grip 을 쓴다.

import cv2
import tm
import robotvision
import dobotkit

# 1) 카메라를 켠다
카메라 = cv2.VideoCapture(0)

# 2) 내가 티처블머신에서 저장한 모델을 불러온다
모델 = tm.load_model('분리수거.npz')

# 3) 사진 한 장을 찍는다
찍힘, 사진 = 카메라.read()

# 4) 무엇인지 물어본다 — 이름표(캔·플라스틱·종이)와 확신(0~1)
이름표, 확신 = 모델.predict(사진)
print('무엇:', 이름표, 확신)

# 5) 어디 있는지 물어본다 — 화면에서 가장 큰 덩어리의 가운데 점(픽셀)
자리 = robotvision.find_object(사진)
print('어디(픽셀):', 자리)

# 6) 로봇팔을 준비한다
팔 = dobotkit.MagicianLite()
팔.home()

# 7) 픽셀 자리를 로봇 자리(mm)로 바꾼다.
#    물건을 못 찾았으면 늘 쓰던 가운데 자리로 간다.
if 자리 is None:
    print('물건을 못 찾았어요 — 매트 위에 하나만 올려 주세요')
    로봇x = 200
    로봇y = 0
else:
    로봇x, 로봇y = robotvision.to_robot(자리[0], 자리[1])
print('로봇 자리(mm):', 로봇x, 로봇y)

# 8) 그 자리로 가서 집는다
팔.move_to(로봇x, 로봇y, 40)
팔.grip(True)

# 9) 바람을 끄지 않으면 계속 돌아간다 — 코드 마지막은 언제나 펌프 정지.
#    (여기서 집게가 풀리지만, 바람을 켠 채로 프로그램을 끝내면 안 된다.
#     들고 옮기는 것은 다음 단계 ③놓기 에서 배운다.)
팔.pump_off()
