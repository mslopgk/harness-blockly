# [H1-①] 알아듣기 — 말에서 '동작'과 '자리'를 뽑아낸다 (로봇 없음)
#
# 고등 1차시를 세 단계로 나눈 첫 번째 파일이다(알아듣기 → 움직이기 → 대화하기).
# 이 단계는 로봇을 쓰지 않는다. 자연어 문장을 읽어 무엇을 시키는 말인지
# 함수로 해석하는 것까지가 목표다.
# (원래 수업은 VLM(눈)+LLM(두뇌)로 VLA 를 하지만, 여기선 파이썬으로 명령 해석기를 직접 만든다.)
#
# 블록으로도 깔끔히 펼쳐지도록 try/except·컴프리헨션·데코레이터는 쓰지 않는다.

# 미리 정해둔 자리 (2차시에서는 카메라 캘리브레이션으로 픽셀→로봇 좌표를 구한다)
자리표 = {
    '왼쪽': (150, 100, 40),
    '가운데': (200, 0, 40),
    '오른쪽': (150, -100, 40),
}


def parse_command(문장):
    """자연어 문장에서 동작(집기/놓기)과 자리 이름을 뽑아낸다."""
    동작 = None
    if '집' in 문장:
        동작 = 'pick'
    elif '놓' in 문장 or '내려' in 문장:
        동작 = 'place'

    자리 = None
    for 이름 in 자리표:
        if 이름 in 문장:
            자리 = 이름
    return 동작, 자리


# 시험 삼아 몇 문장을 넣어 본다
연습문장 = ['왼쪽 물건 집어', '가운데에 놓아', '오른쪽으로 내려', '안녕']
for 문장 in 연습문장:
    동작, 자리 = parse_command(문장)
    print(문장, '->', 동작, 자리)
