# [H1-③] 대화하기 — 말로 시키면 알아듣고 계속 움직인다 (고등 1차시 완성본)
# [H1] 자연어로 로봇 제어 — 말로 지시하면 로봇팔이 알아듣고 움직인다
#
# ①알아듣기 + ②움직이기 를 그대로 담고 있고, 뒤에 '입력 루프'가 붙었다.
# 이 파일 하나만 열어도 처음부터 끝까지 돌아간다.
#
# 고등 파이썬 수업: 자연어(키워드) 해석 → 동작 매핑을 함수로 구조화한다.
# (원래 수업은 VLM(눈)+LLM(두뇌)로 VLA 를 하지만, 여기선 파이썬으로 명령 해석기를 직접 만든다.)
# 블록으로도 깔끔히 펼쳐지도록 try/except·컴프리헨션·데코레이터는 쓰지 않는다.
import dobotkit

# 미리 정해둔 자리 (2차시에서는 카메라 캘리브레이션으로 픽셀→로봇 좌표를 구한다)
자리표 = {
    '왼쪽': (150, 100, 40),
    '가운데': (200, 0, 40),
    '오른쪽': (150, -100, 40),
}


def parse_command(문장):
    """자연어 문장에서 동작(집기/놓기)과 자리 이름을 뽑아낸다."""
    동작 = None
    if '집' in 문장:
        동작 = 'pick'
    elif '놓' in 문장 or '내려' in 문장:
        동작 = 'place'

    자리 = None
    for 이름 in 자리표:
        if 이름 in 문장:
            자리 = 이름
    return 동작, 자리


def run_command(팔, 문장):
    """해석한 명령을 로봇팔 동작으로 실행한다."""
    동작, 자리 = parse_command(문장)
    if 자리 is not None:
        x, y, z = 자리표[자리]
        팔.move_to(x, y, z)
    if 동작 == 'pick':
        팔.suck(True)
    elif 동작 == 'place':
        팔.suck(False)
    else:
        print('무슨 동작인지 모르겠어요:', 문장)


def main():
    팔 = dobotkit.MagicianLite()
    팔.set_speed(50, 50)
    팔.home()

    print('명령을 말해보세요. (예: "왼쪽 물건 집어", "가운데에 놓아")  끝내려면 "끝"')
    while True:
        문장 = input('명령> ')
        if 문장 == '끝' or 문장 == '':
            break
        run_command(팔, 문장)

    팔.home()
    print('종료합니다. 마지막 위치:', 팔.get_pose())

    # 바람을 끄지 않으면 계속 돌아간다 — 코드 마지막은 언제나 펌프 정지
    팔.pump_off()


if __name__ == '__main__':
    main()
