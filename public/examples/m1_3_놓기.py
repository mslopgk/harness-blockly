# [중등 1-③] 놓기 — 이름표대로 함에 옮겨 놓고 마무리 (1차시 완성본)
#
# ①찾기 + ②잡기 를 그대로 담고 있고, 뒤에 '옮겨 놓기'가 붙었다.
# 이 파일 하나만 열어도 처음부터 끝까지 돌아간다.
#
# 오늘 만드는 로봇: 카메라로 보고(무엇·어디) → 그 자리로 가서 집고 →
# 이름표대로 함 A(캔)·함 B(플라스틱)·함 C(종이) 에 내려놓는다.
#
# 블록 수업용이라 try/except 같은 어려운 것은 쓰지 않고, 변수 이름은 한국어로 둔다.
# 이 수업 로봇에 달린 것은 **집게(그리퍼)** 라서 grip 을 쓴다.

import cv2
import tm
import robotvision
import dobotkit

# 1) 카메라를 켠다
카메라 = cv2.VideoCapture(0)

# 2) 내가 티처블머신에서 저장한 모델을 불러온다
모델 = tm.load_model('분리수거.npz')

# 3) 사진 한 장을 찍는다
찍힘, 사진 = 카메라.read()

# 4) 무엇인지 물어본다 — 이름표(캔·플라스틱·종이)와 확신(0~1)
이름표, 확신 = 모델.predict(사진)
print('무엇:', 이름표, 확신)

# 5) 어디 있는지 물어본다 — 화면에서 가장 큰 덩어리의 가운데 점(픽셀)
자리 = robotvision.find_object(사진)
print('어디(픽셀):', 자리)

# 6) 로봇팔을 준비한다
팔 = dobotkit.MagicianLite()
팔.home()

# 7) 픽셀 자리를 로봇 자리(mm)로 바꾼다.
#    ※ 미리 로봇 패널 → '자리 맞추기'를 한 번 해 두어야 한다.
#    물건을 못 찾았으면 늘 쓰던 가운데 자리로 간다.
if 자리 is None:
    print('물건을 못 찾았어요 — 매트 위에 하나만 올려 주세요')
    로봇x = 200
    로봇y = 0
else:
    로봇x, 로봇y = robotvision.to_robot(자리[0], 자리[1])
print('로봇 자리(mm):', 로봇x, 로봇y)

# 8) 그 자리로 가서 집는다
팔.move_to(로봇x, 로봇y, 40)
팔.grip(True)

# 9) 갈림길 — 확신이 낮으면 옮기지 않고 잠깐 멈춘다.
#    아니면 이름표대로 함 A(캔) · 함 B(플라스틱) · 함 C(종이) 로 옮긴다.
if 확신 < 0.8:
    print('잘 모르겠어요')
elif 이름표 == '캔':
    팔.move_to(150, 100, 40)
elif 이름표 == '플라스틱':
    팔.move_to(150, 0, 40)
else:
    팔.move_to(150, -100, 40)

# 10) 내려놓고 처음 자리로
팔.grip(False)
팔.home()

# 11) 바람을 끄지 않으면 계속 돌아간다 — 코드 마지막은 언제나 펌프 정지
팔.pump_off()
