# [중등 2-①] 손보기 — 사람이 무슨 손을 냈는지 알아보기
#
# 2차시를 세 단계로 나눈 첫 번째 파일이다(손보기 → 응수하기 → 대전하기).
# 이 단계는 **로봇을 쓰지 않는다**. 카메라로 손 사진을 찍어서 가위·바위·보 중
# 무엇인지 모델에게 물어보는 것까지가 목표다.
#
# 2차시는 **자리 맞추기(캘리브레이션)가 필요 없다**. 로봇은 제자리에서 집게만
# 여닫기 때문에 카메라 픽셀을 로봇 좌표로 바꿀 일이 없다.
#
# 블록 수업용이라 try/except 같은 어려운 것은 쓰지 않고, 변수 이름은 한국어로 둔다.

import cv2
import tm

# 1) 카메라를 켠다
카메라 = cv2.VideoCapture(0)

# 2) 내가 저장한 가위바위보 모델을 불러온다
모델 = tm.load_model('가위바위보.npz')

# 3) 사람 손을 사진으로 찍는다
찍힘, 사진 = 카메라.read()

# 4) 무슨 손인지 물어본다 — 이름표(가위·바위·보)와 확신(0~1)
이름표, 확신 = 모델.predict(사진)
print('사람:', 이름표, 확신)

# 5) 확신이 낮으면 잘 안 보인 것이다
if 확신 < 0.8:
    print('잘 모르겠어요 — 손을 카메라에 더 크게 보여 주세요')
