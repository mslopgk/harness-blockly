# [중등 1-①] 찾기 — 무엇인지 + 어디 있는지 알아보기
#
# 1차시를 세 단계로 나눈 첫 번째 파일이다(찾기 → 잡기 → 놓기).
# 이 단계는 **로봇을 쓰지 않는다**. 카메라로 사진을 한 장 찍어서
#   · 무엇인지  → 내가 가르친 모델에게 물어본다(모델.predict)
#   · 어디 있는지 → 화면에서 가장 큰 덩어리를 찾는다(robotvision.find_object)
# 이 둘을 print 로 확인하는 것까지가 오늘의 목표다.
#
# 블록 수업용이라 try/except 같은 어려운 것은 쓰지 않는다.
# 변수 이름은 블록 안에 그대로 보이므로 한국어로 둔다.

import cv2
import tm
import robotvision

# 1) 카메라를 켠다
카메라 = cv2.VideoCapture(0)

# 2) 내가 티처블머신에서 저장한 모델을 불러온다
모델 = tm.load_model('분리수거.npz')

# 3) 사진 한 장을 찍는다
찍힘, 사진 = 카메라.read()

# 4) 무엇인지 물어본다 — 이름표(캔·플라스틱·종이)와 확신(0~1)
이름표, 확신 = 모델.predict(사진)
print('무엇:', 이름표, 확신)

# 5) 어디 있는지 물어본다 — 화면에서 가장 큰 덩어리의 가운데 점(픽셀)
#    물건이 없으면 None 이 나온다.
자리 = robotvision.find_object(사진)
print('어디(픽셀):', 자리)
