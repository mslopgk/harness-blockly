# [중등 2-③] 대전하기 — 다섯 판을 겨루고 마무리 (2차시 완성본)
#
# ①손보기 + ②응수하기 를 그대로 담고 있고, 그것을 다섯 번 되풀이한다.
# 이 파일 하나만 열어도 처음부터 끝까지 돌아간다.
#
# 로봇은 **제자리에서 집게만 여닫는다** — move_to 를 쓰지 않는다.
#   강의자료가 안전 근거로 반복해 약속한 내용이기 때문이다:
#   03_교사_사전준비_안전.md:191 "로봇은 이동하지 않습니다",
#   교사가 그대로 읽는 안전 대본 :289 "오늘 로봇은 제자리에서 집게만 여닫습니다".
# 그래서 2차시는 자리 맞추기(캘리브레이션)도 필요 없다.
#
# 로봇 수 ↔ 집게 동작 대응은 강의자료와 같다: 바위=닫기 · 보=펴기 · 가위=바람 끄기.
# 블록 수업용이라 try/except 같은 어려운 것은 쓰지 않고, 변수 이름은 한국어로 둔다.

import cv2
import tm
import dobotkit

# 1) 카메라를 켠다
카메라 = cv2.VideoCapture(0)

# 2) 내가 저장한 가위바위보 모델을 불러온다
모델 = tm.load_model('가위바위보.npz')

# 3) 로봇팔을 준비한다 — 판을 시작할 때 집게를 펴 둔다
팔 = dobotkit.MagicianLite()
팔.grip(False)

# 4) 다섯 판을 겨룬다
for 판 in range(5):
    print('---', 판 + 1, '번째 판 ---')

    # 사람 손을 사진으로 찍어서 무엇인지 물어본다
    찍힘, 사진 = 카메라.read()
    이름표, 확신 = 모델.predict(사진)
    print('사람:', 이름표, 확신)

    # 갈림길 — 확신이 낮으면 이번 판은 건너뛴다. 아니면 이기는 손을 낸다.
    if 확신 < 0.8:
        로봇 = '없음'
        print('잘 모르겠어요 — 다시 내 주세요')
    elif 이름표 == '가위':
        로봇 = '바위'
        팔.grip(True)
    elif 이름표 == '바위':
        로봇 = '보'
        팔.grip(False)
    else:
        로봇 = '가위'
        팔.pump_off()

    print('로봇:', 로봇)

# 5) 판이 끝나면 집게를 펴 둔다
팔.grip(False)
print('오늘 대전 끝!')

# 6) 바람을 끄지 않으면 계속 돌아간다 — 코드 마지막은 언제나 펌프 정지
팔.pump_off()
